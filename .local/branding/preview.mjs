import fs from 'node:fs';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const puppeteer=require('../browser/node_modules/puppeteer-core');
const browser=await puppeteer.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--no-sandbox','--disable-gpu']});
const errors=[];
const page=await browser.newPage();
page.on('pageerror',error=>errors.push(error.message));
await page.setViewport({width:1440,height:1000,deviceScaleFactor:1});
await page.goto('http://localhost/learning-bapanas/',{waitUntil:'networkidle2',timeout:90000});
await page.screenshot({path:'.local/branding/desktop.png',fullPage:true});
fs.writeFileSync('.local/branding/home-dom.html',await page.content());
console.log('Desktop',await page.evaluate(()=>({title:document.title,width:innerWidth,scroll:document.documentElement.scrollWidth,text:document.body.innerText.slice(0,1800)})));
await page.setViewport({width:390,height:844,deviceScaleFactor:1});
await page.reload({waitUntil:'networkidle2',timeout:90000});
await page.screenshot({path:'.local/branding/mobile.png',fullPage:true});
console.log('Mobile',await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth})));
await page.goto('http://localhost/learning-bapanas/login/index.php',{waitUntil:'networkidle2',timeout:90000});
await page.screenshot({path:'.local/branding/login.png',fullPage:true});
console.log('Browser errors',errors);
await browser.close();
